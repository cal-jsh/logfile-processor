/// Default cap on the number of result lines (matches + context) sent per request.
/// The browser keeps every result line in memory, so this protects the tab until the
/// viewer moves to a windowed/streaming model.
pub const DEFAULT_MAX_LINES: usize = 100_000;

pub fn router() -> Router {
    Router::new()
        .route("/stream_logs", get(stream_filtered_logs))
        .route("/close_session", post(close_session))
}

fn json_event(value: &serde_json::Value) -> Event {
    Event::default().data(serde_json::to_string(value).unwrap())
}

fn line_event(o: OutputLine) -> Event {
    json_event(&json!({
        "type": "line",
        "line_number": o.line_number,
        "line": o.line,
        "context": o.context,
    }))
}

/// Final event of a result stream. `truncated` is true when more result lines existed
/// beyond `max_lines` and were not sent.
fn end_event(emitted: usize, max_lines: usize, truncated: bool, lines_scanned: u64) -> Event {
    json_event(&json!({
        "type": "end",
        "emitted": emitted,
        "max_lines": max_lines,
        "truncated": truncated,
        "lines_scanned": lines_scanned,
    }))
}

#[derive(Deserialize)]
pub struct LogFilterQuery {
    pub session_id: String,
    pub domains: Option<String>,
    pub levels: Option<String>,
    pub keywords: Option<String>,
    /// Optional context window size. If absent or zero -> no context expansion.
    pub context: Option<usize>,
    /// Maximum number of result lines to send (defaults to [`DEFAULT_MAX_LINES`]).
    pub max_lines: Option<usize>,
}

struct ScanState {
    reader: BufReader<File>,
    buf: Vec<u8>,
    filter: LineFilter,
    window: ContextWindow,
    line_number: u64,
    emitted: usize,
    max_lines: usize,
    finished: bool,
}

/// Read the next line as text, without its line terminator. Invalid UTF-8 is replaced
/// rather than aborting the stream, so line numbering stays aligned with the file.
async fn next_line(reader: &mut BufReader<File>, buf: &mut Vec<u8>) -> std::io::Result<Option<String>> {
    buf.clear();
    if reader.read_until(b'\n', buf).await? == 0 {
        return Ok(None);
    }
    if buf.last() == Some(&b'\n') {
        buf.pop();
        if buf.last() == Some(&b'\r') {
            buf.pop();
        }
    }
    Ok(Some(String::from_utf8_lossy(buf).into_owned()))
}

/// Produce the next batch of SSE events: the result lines generated by the next
/// line that yields any output, or the final `end` event.
async fn next_batch(mut st: ScanState) -> Option<(Vec<Event>, ScanState)> {
    if st.finished {
        return None;
    }
    loop {
        let line = match next_line(&mut st.reader, &mut st.buf).await {
            Ok(Some(line)) => line,
            Ok(None) => {
                st.finished = true;
                let end = end_event(st.emitted, st.max_lines, false, st.line_number);
                return Some((vec![end], st));
            }
            Err(err) => {
                warn!("Error reading log file at line {}: {}", st.line_number + 1, err);
                st.finished = true;
                let end = end_event(st.emitted, st.max_lines, false, st.line_number);
                return Some((vec![end], st));
            }
        };
        st.line_number += 1;

        let matched = st.filter.matches(&line);
        let out = st.window.push(st.line_number, line, matched);
        if out.is_empty() {
            continue;
        }

        let mut events = Vec::with_capacity(out.len() + 1);
        for o in out {
            if st.emitted >= st.max_lines {
                // There is at least one more result line than we are allowed to send.
                st.finished = true;
                events.push(end_event(st.emitted, st.max_lines, true, st.line_number));
                return Some((events, st));
            }
            events.push(line_event(o));
            st.emitted += 1;
        }
        return Some((events, st));
    }
}

#[utoipa::path(
    get,
    path = "/stream_logs",
    params(
        ("session_id" = String, Query, description = "Log session ID"),
        ("domains" = Option<String>, Query, description = "Comma-separated log domains to include"),
        ("levels" = Option<String>, Query, description = "Comma-separated log levels to include"),
        ("keywords" = Option<String>, Query, description = "Comma-separated keywords to include"),
        ("context" = Option<usize>, Query, description = "Optional number of surrounding lines to include (±context)"),
        ("max_lines" = Option<usize>, Query, description = "Maximum number of result lines to send (default 100000)")
    ),
    responses(
        (
            status = 200,
            description = "Stream of filtered log events. Each line event is \
                `{type: \"line\", line_number, line, context}` where line_number is the 1-based \
                line in the file. The stream ends with `{type: \"end\", emitted, max_lines, truncated, lines_scanned}`, \
                followed only by keep-alive comments.",
            content_type = "text/event-stream"
        ),
        (
            status = 404,
            description = "Session ID not found"
        )
    ),
    tag = "Log Streaming"
)]
pub async fn stream_filtered_logs(
    Query(query): Query<LogFilterQuery>,
) -> Sse<Pin<Box<dyn futures::Stream<Item = Result<Event, Infallible>> + Send>>> {
    debug!(
        "Logfile filter request: Keywords {:?}, Domains {:?}, Levels {:?}, Context {:?}, Max lines {:?}",
        &query.keywords, &query.domains, &query.levels, &query.context, &query.max_lines
    );

    let file_path = match get_user_log(&query.session_id) {
        Some(path) => path,
        None => return Sse::new(stream::empty().boxed()),
    };

    let file = match File::open(file_path).await {
        Ok(f) => f,
        Err(err) => {
            debug!(
                "Failed to open log file for session {}: {}",
                &query.session_id, err
            );
            return Sse::new(stream::empty().boxed());
        }
    };

    let state = ScanState {
        reader: BufReader::new(file),
        buf: Vec::new(),
        filter: LineFilter::from_csv(
            query.levels.as_deref(),
            query.domains.as_deref(),
            query.keywords.as_deref(),
        ),
        window: ContextWindow::new(query.context.unwrap_or(0)),
        line_number: 0,
        emitted: 0,
        max_lines: query.max_lines.unwrap_or(DEFAULT_MAX_LINES),
        finished: false,
    };

    let file_emits = stream::unfold(state, next_batch)
        .flat_map(stream::iter)
        .map(Ok::<Event, Infallible>);

    // Keep the connection open after the end event (an EventSource reconnects, and so
    // re-runs the query, when the server closes the stream). Clients close it on `end`.
    let heartbeat = stream::unfold(interval(Duration::from_secs(15)), |mut intv| async move {
        intv.tick().await;
        Some((Ok(Event::default().comment("hb")), intv))
    });

    Sse::new(file_emits.chain(heartbeat).boxed())
}

#[utoipa::path(
    post,
    path = "/close_session",
    request_body = CloseSessionQuery,
    responses(
        (status = 200, description = "Session log cleaned up successfully")
    )
)]
pub async fn close_session(Query(query): Query<CloseSessionQuery>) -> Json<&'static str> {
    remove_user_log(&query.session_id);
    info!("Removed log for session_id: {}", &query.session_id);
    Json("ok")
}
